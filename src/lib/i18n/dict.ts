export const DICTS: Record<Locale, Dict> = { tr, en, ky, ru };

export type TFunction = (key: DictKey, vars?: Record<string, string | number>) => string;

/** Sözlükten çeviri fonksiyonu üretir (istemci yalnızca kendi dilinin sözlüğünü alır). */
export function makeTFromDict(dict: Dict): TFunction {
  return (key, vars) => {
    let s = dict[key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

export function makeT(locale: Locale): TFunction {
  return makeTFromDict(DICTS[locale]);
}
